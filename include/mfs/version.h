#ifndef MFS_VERSION_H
#define MFS_VERSION_H

/*
 * MFS library version.
 *
 * These values identify the MFS implementation and its host-side tools.
 * They do not define the on-disk format version or compatibility rules.
 *
 * Versioning follows MAJOR.MINOR.PATCH. The initial 0.x series denotes
 * an unstable development interface.
 */

#define MFS_VERSION_MAJOR 0
#define MFS_VERSION_MINOR 1
#define MFS_VERSION_PATCH 0

#define MFS_VERSION_STRING "0.1.0"

#endif /* MFS_VERSION_H */
